CREATE TABLE "AdminLoyaltyAccount" (
 "userId" TEXT PRIMARY KEY REFERENCES "User"(id) ON DELETE CASCADE,
 points INTEGER NOT NULL DEFAULT 0 CHECK(points BETWEEN 0 AND 1000000),
 revision INTEGER NOT NULL DEFAULT 0 CHECK(revision>=0),
 "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "AdminLoyaltyEntry" (
 id TEXT PRIMARY KEY,
 "userId" TEXT NOT NULL REFERENCES "User"(id) ON DELETE CASCADE,
 "actorId" TEXT REFERENCES "User"(id) ON DELETE SET NULL,
 kind TEXT NOT NULL CHECK(kind IN ('ADJUSTMENT','EXTENSION_REWARD')),
 delta INTEGER NOT NULL CHECK(delta<>0),
 "balanceAfter" INTEGER NOT NULL CHECK("balanceAfter" BETWEEN 0 AND 1000000),
 reason TEXT NOT NULL CHECK(char_length(reason) BETWEEN 5 AND 500),
 "listingId" TEXT,
 "createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "AdminLoyaltyEntry_user_date_idx" ON "AdminLoyaltyEntry"("userId","createdAt" DESC);
